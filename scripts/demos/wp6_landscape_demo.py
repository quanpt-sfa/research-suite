"""End-to-end CLI demo of WP6 (the landscape) in a throw-away store. No network and no real model: the reader and the adjudicator are scripted.
The papers are invented (tests/landscape_fixture.py): two works that contradict each other on one relationship, two versions of one work whose finding
reverses, a paper on another relationship, and one paper held as an abstract only.

    python scripts/demos/wp6_landscape_demo.py
"""
from __future__ import annotations

import io
import json
import sys
import tempfile
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from research_harness import cli_knowledge  # noqa: E402
from research_harness.cli import main  # noqa: E402
from research_harness.discovery import landscape as L  # noqa: E402
from research_harness.workflows.adapters import ScriptedModelAdapter  # noqa: E402
from tests import landscape_fixture as F  # noqa: E402

ADJ_OK = {"passage_proposition": "As quoted.", "equivalence": "EQUIVALENT", "dropped_conditions": [], "cue_handling": [], "verdict": "SUPPORTED_AS_STATED",
          "required_qualification": [], "rationale": "The restatement says what the quote says."}
READ = F.reader().custom_handler
SHOWN: dict[str, str] = {}


def both(system: str, user: str):
    return dict(ADJ_OK) if "adversarial checker" in system else READ(system, user)


def run(*argv: str) -> str:
    shown = " ".join(f'"{a}"' if " " in a else a for a in argv)
    for real, alias in SHOWN.items():
        shown = shown.replace(real, alias)
    print("$ research " + shown)
    out, err = io.StringIO(), io.StringIO()
    with redirect_stdout(out), redirect_stderr(err):
        rc = main(list(argv))
    text = out.getvalue().rstrip() or err.getvalue().rstrip()
    for real, alias in SHOWN.items():
        text = text.replace(real, alias)
    print(text)
    if rc:
        print(f"(exit {rc})")
    print()
    return text


def main_demo() -> None:
    cli_knowledge._adapter = lambda args: ScriptedModelAdapter(model_id="scripted-reader", custom_handler=both)
    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        w = F.build_world(tmp_path, search=False, make_run=False)
        store, token, home = w["store"], w["token"], w["home"]
        tf = tmp_path / "token"
        tf.write_text(token, encoding="utf-8")
        export_dir = tmp_path / "export"
        crit = tmp_path / "criteria.json"
        SHOWN.update({str(home): "<home>", str(tf): "<token-file>", str(export_dir): "<export-dir>", str(crit): "<criteria.json>"})
        base = ["--project", "PRJ_LAND", "--home", str(home)]
        auth = [*base, "--token-file", str(tf)]
        print("# WP6 demo: from a searched reading list to a landscape, over five invented papers\n")
        pid = w["pid"]
        run("retrieval", "new", pid, "--term", F.TERMS[0], "--label", "Detection models and manipulation", *auth)
        run("retrieval", "search", "RET_000001", *auth)
        print("# 1. build: every record is quote-verified; the evidence of a version stays at that version (the retrieved one is read by default)\n")
        run("landscape", "build", "RET_000001", *auth)
        shown = run("landscape", "show", "LAND_000001", *base)
        print("# 2. the reading dimension moves only through ECA and your confirmation; a model proposal alone does not move it\n")
        v = L.view(store, "LAND_000001")
        e = next(x for x in v["entries"] if x["source_id"] == "SRC_PAT" and x["category"] == "finding")
        passage = e["author_claim"]["passage_id"]
        SHOWN[passage] = "<passage>"
        adj = run("adjudicate", "run", "--statement", "LAND_000001", "--element", e["id"], "--passage", passage, *auth)
        adj_id = adj.split()[0]
        run("adjudicate", "confirm", adj_id, "--verdict", "SUPPORTED_AS_STATED", "--rationale", "The restatement is a fair reading of the quote.", *auth)
        print("# 3. your decision on the suite's inference; the inference stays PROVISIONAL and generated by the suite\n")
        run("landscape", "review", "LAND_000001", "I001", "NEEDS_SCOPE", "--reason", "One measures accruals, the other real earnings management: check the populations before calling it a conflict.", *auth)
        print("# 4. a method assessment is yours alone, and its verdict is capped by the rule (no methodological-literature basis -> LIMITED)\n")
        crit.write_text(json.dumps([{"criterion": "Parallel pre-trends hold in an event study", "basis": "the paper's own event study", "methodological_literature": False, "met": "yes"}]), encoding="utf-8")
        run("landscape", "assess", "LAND_000001", e["id"], "--verdict", "SUPPORTED_WITHIN_SCOPE", "--criteria", str(crit),
            "--threats", json.dumps([{"threat": "Concurrent regulatory changes", "status": "addressed"}]), "--rationale", "Looks sound to me, but I only have the paper's own basis.", *auth)
        run("landscape", "show", "LAND_000001", *base)
        print("# 5. reading every held version of each work: a reversal between versions is a version difference, never a contradiction between studies\n")
        run("landscape", "build", "RET_000001", "--versions", "all", "--label", "All versions", *auth)
        text = run("landscape", "show", "LAND_000002", *base)
        print("# 6. export, and verification against the store\n")
        run("export", "landscape", "LAND_000001", "--out", str(export_dir), *base)
        run("export", "verify", str(export_dir), *base)
        for name in ("research_landscape.md",):
            print(f"----- {name} (first lines) -----")
            print("\n".join((export_dir / name).read_text(encoding="utf-8").splitlines()[:34]))
            print()
        print("# 7. the problem is reframed: the landscape (and the run it came from) no longer describe it\n")
        run("problem", "revise", pid, "--rationale", "the question is about disclosure only", "--statement", "Disclosure by firms after detection models spread is not understood.", *auth)
        run("landscape", "show", "LAND_000001", *base)
        run("landscape", "build", "RET_000001", *auth)
        del shown, text


if __name__ == "__main__":
    main_demo()
