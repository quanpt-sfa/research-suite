"""Turn a static discipline profile into scoped `KnowledgeItem` proposals (plan v3, Phase 3A.1c).

A discipline profile is a list of items to consider, written for one tradition and one set of data sources. It is not a
definition of the field. Migrated, each item becomes a `KnowledgeItem` of kind `checklist` that:

* states its **scope** exactly as far as the profile does: the domain, and the data sources the profile itself lists as
  its preferred evidence (no jurisdiction or period is inferred that the profile does not state);
* carries an **exclusion** saying it is not established outside that scope;
* starts at `source_fidelity=NOT_CHECKED`, `methodological_validity=[]`, generated by `import`, with no evidence basis,
  so it cannot be promoted into a shared library until someone gives it one (invariant I9/I14).

The result is a list of `propose_object` operations. They become a proposal by adding the project's snapshot as `base`
(`build_proposal`) and are imported through the normal gateway; nothing is written here.
"""
from __future__ import annotations

import re
from typing import Any, Optional

from research_harness import taxonomy
from research_harness.workflows.profiles.registry import get_profile

_DOMAIN_OF_PROFILE = {"accounting": "accounting", "finance": "finance", "education": "education"}


def _object_id(profile_id: str, key: str, taken: set[str]) -> str:
    stem = re.sub(r"[^A-Z0-9]+", "_", f"KI_PROFILE_{profile_id}_{key}".upper()).strip("_")[:60]
    candidate, n = stem, 1
    while candidate in taken:
        n += 1
        candidate = f"{stem[:56]}_{n}"
    taken.add(candidate)
    return candidate


def profile_knowledge_operations(profile_id: str) -> list[dict[str, Any]]:
    """`propose_object` operations: one scoped KnowledgeItem per checklist item and per validity question."""
    prof = get_profile(profile_id)
    domain = _DOMAIN_OF_PROFILE.get(prof.identifier)
    if domain is None:
        raise KeyError(f"No domain is declared for profile '{profile_id}'; add it to _DOMAIN_OF_PROFILE after checking its scope.")
    taxonomy.validate_domain(domain)
    scope = {"domain": domain, "data_regime": {"data_source": list(prof.preferred_evidence_types)}}
    exclusions = [f"Not established outside the data sources this profile lists ({'; '.join(prof.preferred_evidence_types)}); "
                  f"the '{prof.identifier}' profile is one tradition's checklist, not the field."]
    validation = {"source_fidelity": "NOT_CHECKED", "computational_reproducibility": "NOT_ATTEMPTED", "methodological_validity": []}

    taken: set[str] = set()
    ops: list[dict[str, Any]] = []

    def add(kind_label: str, key: str, label: str, prompt: str, group: str) -> None:
        ops.append({
            "operation": "propose_object", "proposed_id": _object_id(prof.identifier, key, taken), "object_type": "KnowledgeItem",
            "content": {
                "label": label[:300], "description": prompt, "kind": "checklist", "group": group, "scope": scope,
                "exclusions": exclusions, "validation": validation, "generated_by": "import", "evidence_basis": [],
                "attributes": {"origin": f"profile:{prof.identifier}", "profile_title": prof.title},
            },
            "relations": [],
        })

    for item in prof.methodological_checklist:
        add("checklist", item["item"], item["item"].replace("_", " "), item["prompt"], "methodological_checklist")
    for i, question in enumerate(prof.validity_questions, 1):
        add("checklist", f"VALIDITY_{i}", f"{prof.identifier} validity question {i}", question, "validity_question")
    return ops


def build_proposal(project_id: str, snapshot: dict[str, Any], proposal_id: str, operations: list[dict[str, Any]],
                   *, origin_channel: str = "human_cli", note: str = "") -> dict[str, Any]:
    """Wrap operations in a proposal document based on a snapshot of the target project."""
    from research_harness import PROTOCOL_VERSION
    return {
        "protocol_version": PROTOCOL_VERSION, "proposal_id": proposal_id, "project_id": project_id,
        "base": {"snapshot_id": snapshot["snapshot_id"], "state_revision": snapshot["state_revision"],
                 "state_sha256": snapshot["state_sha256"]},
        "read_set": dict(snapshot.get("object_revisions", {})), "origin_channel": origin_channel,
        "operations": operations, **({"note": note} if note else {}),
    }
